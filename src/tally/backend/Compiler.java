package tally.backend;

import java.util.List;

import tally.front.Ast;
import tally.front.Checker;
import tally.front.Parser;
import tally.ir.Function;
import tally.ir.Lowering;
import tally.opt.Pipeline;

/** Source text in, TVM assembly out: parse, check, lower, optimise, allocate, emit. */
public final class Compiler {
    private Compiler() {}

    public static String compile(String source, int level, StringBuilder irDump) {
        Ast.Program program = Parser.parse(source);
        Checker.check(program);
        List<Function> functions = Lowering.lower(program);
        StringBuilder asm = new StringBuilder();
        asm.append("; generated by tallyc -O").append(level).append('\n');
        for (Function f : functions) {
            Pipeline.optimise(f, level);
            LinearScan alloc = LinearScan.allocate(f);
            if (irDump != null) {
                irDump.append(f.dump());
                irDump.append("  intervals: ").append(alloc.intervals.all).append('\n');
                irDump.append("  locations: ").append(alloc.where).append('\n');
            }
            CodeGen.emit(f, alloc, asm);
        }
        return asm.toString();
    }
}
